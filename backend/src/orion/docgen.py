"""Write docs/queries.md: every named Cypher query in queries.py, with the modules that run it.

    uv run python -m orion.docgen
"""

from __future__ import annotations

import re
from pathlib import Path

from orion.queries import Q

ROOT = Path(__file__).resolve().parents[3]
SRC = Path(__file__).resolve().parent


def users() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {name: [] for name in Q}
    for f in sorted(SRC.rglob("*.py")):
        if f.name in ("queries.py", "docgen.py"):
            continue
        text = f.read_text()
        for name in re.findall(r'cypher\("([a-z_]+)"\)', text):
            mod = str(f.relative_to(SRC)).removesuffix(".py").replace("/", ".")
            if name in out and mod not in out[name]:
                out[name].append(mod)
    return out


def main() -> None:
    used = users()
    lines = ["# Queries", "",
             "Every named Cypher query Orion runs, from `backend/src/orion/queries.py`, with the modules that run it.",
             "Read tools run them through `GRAPH.RO_QUERY`, so none of them can write. Generated by "
             "`uv run python -m orion.docgen`.", "",
             f"{len(Q)} named queries. Writes (loading, forking, merging, the board) are inline in the modules that make them.",
             ""]
    for name, text in Q.items():
        mods = ", ".join(f"`{m}`" for m in used[name]) or "not called by name"
        lines += [f"## `{name}`", "", f"Used by {mods}.", "", "```cypher", text.strip(), "```", ""]
    (ROOT / "docs" / "queries.md").write_text("\n".join(lines))
    print(f"wrote docs/queries.md: {len(Q)} queries")


if __name__ == "__main__":
    main()
